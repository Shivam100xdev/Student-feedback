#!/usr/bin/env node
/**
 * One-command local database setup:
 *   1. start the Postgres container (docker compose up -d)
 *   2. wait until its healthcheck reports "healthy"
 *   3. apply Drizzle migrations
 *   4. seed the demo college accounts
 *
 * Usage: npm run db:setup
 *
 * Waiting on the healthcheck is the point: `docker compose up -d` returns as
 * soon as the container starts, but Postgres still needs a moment to accept
 * connections, which made `db:migrate` fail on a fresh clone.
 */
import { spawnSync } from "node:child_process";
import { copyFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const envFile = join(root, ".env");
const envLocalFile = join(root, ".env.local");
const envExampleFile = join(root, ".env.example");

const CONTAINER = "feedback-postgres";
const DEFAULT_DATABASE_URL = "postgresql://postgres:postgres@localhost:5434/feedback_db";
const HEALTH_TIMEOUT_MS = 120_000;
const POLL_INTERVAL_MS = 2_000;

const isWindows = process.platform === "win32";

function run(command, args, label) {
  console.log(`\n▸ ${label}`);
  // Runs node/docker directly: the npm and npx shims are .cmd files on Windows,
  // which spawnSync cannot execute without a shell.
  const result = spawnSync(command, args, { cwd: root, stdio: "inherit" });

  if (result.error) {
    console.error(`✗ Could not run "${command}": ${result.error.message}`);
    process.exit(1);
  }
  if (result.status !== 0) {
    console.error(`✗ ${label} failed (exit code ${result.status}).`);
    process.exit(result.status ?? 1);
  }
}

function readEnvValue(file, key) {
  if (!existsSync(file)) return undefined;
  for (const line of readFileSync(file, "utf8").split(/\r?\n/)) {
    const match = new RegExp(`^${key}=(.*)$`).exec(line.trim());
    if (match) return match[1];
  }
  return undefined;
}

/**
 * Compose reads `.env` (not `.env.local`) for POSTGRES_PASSWORD, so keep the
 * two files in sync instead of failing on a fresh clone where `.env` is absent.
 */
function ensureComposeEnv() {
  const databaseUrl = readEnvValue(envLocalFile, "DATABASE_URL") || DEFAULT_DATABASE_URL;
  const existing = readEnvValue(envFile, "POSTGRES_PASSWORD");
  if (existing) return;

  let password = "postgres";
  let host = "localhost";
  let port = "5434";
  try {
    const url = new URL(databaseUrl);
    password = decodeURIComponent(url.password) || "postgres";
    host = url.hostname;
    port = url.port || "5432";
  } catch {
    console.warn(`! Could not parse DATABASE_URL, using password "${password}" for the container.`);
  }

  const kept = existsSync(envFile)
    ? readFileSync(envFile, "utf8")
        .split(/\r?\n/)
        .filter((line) => !/^POSTGRES_PASSWORD=/.test(line.trim()))
        .join("\n")
        .trim()
    : "# Docker Compose variables (generated by npm run db:setup)";
  writeFileSync(envFile, `${kept}\nPOSTGRES_PASSWORD=${password}\n`);
  console.log(`✓ Created .env with POSTGRES_PASSWORD matching DATABASE_URL in .env.local`);

  if (host !== "localhost" && host !== "127.0.0.1") {
    console.warn(`! DATABASE_URL points at host "${host}", but the container publishes on localhost:5434.`);
  }
  if (port !== "5434") {
    console.warn(
      `! DATABASE_URL uses port ${port}, but docker-compose publishes Postgres on 5434.\n` +
        `  Update DATABASE_URL in .env.local to ...@localhost:5434/... (port 5432 is often a native Postgres install).`,
    );
  }
}

function containerHealth() {
  const result = spawnSync(
    isWindows ? "docker.exe" : "docker",
    ["inspect", "--format", "{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}", CONTAINER],
    { cwd: root, encoding: "utf8" },
  );
  if (result.error || result.status !== 0) return "missing";
  return result.stdout.trim();
}

async function waitForHealthy() {
  const deadline = Date.now() + HEALTH_TIMEOUT_MS;
  process.stdout.write(`\n▸ Waiting for ${CONTAINER} to become healthy`);
  let last = "";

  while (Date.now() < deadline) {
    const status = containerHealth();
    if (status === "healthy") {
      console.log("\n✓ Postgres is healthy and accepting connections");
      return;
    }
    if (status !== last) {
      last = status;
      process.stdout.write(` [${status}]`);
    } else {
      process.stdout.write(".");
    }
    if (status === "unhealthy") break;
    await new Promise((resolve) => setTimeout(resolve, POLL_INTERVAL_MS));
  }

  console.error(
    `\n✗ ${CONTAINER} did not become healthy within ${HEALTH_TIMEOUT_MS / 1000}s.\n` +
      `  Check the logs with: docker compose logs db`,
  );
  process.exit(1);
}

function ensureEnvLocal() {
  if (existsSync(envLocalFile)) return;
  if (!existsSync(envExampleFile)) return;

  copyFileSync(envExampleFile, envLocalFile);
  const contents = readFileSync(envLocalFile, "utf8")
    .replace(/^DATABASE_URL=.*$/m, `DATABASE_URL=${DEFAULT_DATABASE_URL}`)
    .replace(/^\[TEMPLATE\]\r?\n/m, "");
  writeFileSync(envLocalFile, contents);
  console.log("✓ Created .env.local from .env.example (add your OAuth secrets before signing in)");
}

ensureEnvLocal();
ensureComposeEnv();

run("docker", ["compose", "up", "-d"], "Starting the database container");
await waitForHealthy();

run(process.execPath, ["node_modules/drizzle-kit/bin.cjs", "migrate"], "Applying database migrations");
run(process.execPath, ["scripts/seed-users.mjs"], "Seeding demo accounts");

console.log("\n✅ Database ready. Start the app with: npm run dev");
